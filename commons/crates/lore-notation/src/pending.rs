//! 待補: results a paper still waits for. Four registered draft marks carry the
//! pending item's id, so the paper source itself says where every pending
//! number, table cell, planned paragraph and dependent sentence is:
//!
//! | mark | means | draft PDF |
//! |---|---|---|
//! | `\pending{P1}{Dice on the external set}` | a number that waits for data | boxed `P1: Dice on the external set` |
//! | `\pendingcell{P1}{Ours / Dice}` | a table cell that waits (the argument names the cell) | boxed `P1` |
//! | `\pendingpara{P1}{frame}` | a paragraph whose content is planned but waits | `PENDING P1` + the frame in italics |
//! | `\pendingdep{P1}` | the sentence it ends depends on P1 (written in the expected direction) | superscript `[P1]` |
//!
//! The marks are drawn in [`DRAFT_RGB`], a document colour (never an app theme
//! colour), boxed so they stay visible without colour. Their definitions live in
//! a generated `pending.tex` ([`write_tex`], `\input{pending}` in the preamble);
//! a submission export refuses a paper that still has marks ([`marks`]).
//! The names are reserved (a registry macro can never take them) and the
//! checker skips the ids, so marks never raise findings of their own.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

/// The four mark commands, without the backslash.
pub const MACROS: [&str; 4] = ["pending", "pendingcell", "pendingpara", "pendingdep"];
/// The file the definitions are written to (next to the main file).
pub const FILE: &str = "pending.tex";
pub const GENERATED_HEADER: &str = "% Generated by lore-notation (pending results, 待補) — do not edit; remove \\input{pending} once no mark is left.";
/// The draft colour of the marks (a dark orange that prints well), as LaTeX rgb.
pub const DRAFT_RGB: (f32, f32, f32) = (0.76, 0.25, 0.05);
/// [`DRAFT_RGB`] for HTML previews of the document.
pub const DRAFT_HEX: &str = "#C2400D";

#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum MarkKind {
    /// `\pending{id}{what}`
    Number,
    /// `\pendingcell{id}{cell}`
    Cell,
    /// `\pendingpara{id}{frame}`
    Para,
    /// `\pendingdep{id}`
    Dep,
}

impl MarkKind {
    fn of(name: &str) -> Option<MarkKind> {
        Some(match name {
            "pending" => MarkKind::Number,
            "pendingcell" => MarkKind::Cell,
            "pendingpara" => MarkKind::Para,
            "pendingdep" => MarkKind::Dep,
            _ => return None,
        })
    }
}

/// One mark in a text: byte range of the whole command, its id and argument.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct Mark {
    pub kind: MarkKind,
    pub id: String,
    /// What is measured / the cell / the frame; empty for `\pendingdep`.
    pub arg: String,
    pub start: usize,
    pub end: usize,
}

/// A valid pending id: a letter, then letters, digits or `-` (`P1`, `P12`, `abl-2`).
pub fn valid_id(id: &str) -> bool {
    let mut c = id.chars();
    c.next().is_some_and(|f| f.is_ascii_alphabetic()) && c.all(|x| x.is_ascii_alphanumeric() || x == '-')
}

/// End (exclusive) of the `{…}` group opening at byte `i`, after blanks.
fn group(t: &str, i: usize) -> Option<(usize, usize)> {
    let b = t.as_bytes();
    let mut k = i;
    while k < b.len() && matches!(b[k], b' ' | b'\t' | b'\n' | b'\r') {
        k += 1;
    }
    if b.get(k) != Some(&b'{') {
        return None;
    }
    let mut d = 0i32;
    let mut j = k;
    while j < b.len() {
        match b[j] {
            b'\\' => j += 1,
            b'{' => d += 1,
            b'}' => {
                d -= 1;
                if d == 0 {
                    return Some((k, j + 1));
                }
            }
            _ => {}
        }
        j += 1;
    }
    None
}

/// Every mark in `text`, in order; marks in `%` comments are skipped.
pub fn marks(text: &str) -> Vec<Mark> {
    let b = text.as_bytes();
    let mut out = vec![];
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b'%' => {
                while i < b.len() && b[i] != b'\n' {
                    i += 1;
                }
                continue;
            }
            b'\\' => {
                let s = i;
                let mut j = i + 1;
                while j < b.len() && b[j].is_ascii_alphabetic() {
                    j += 1;
                }
                if j == i + 1 {
                    i += 2; // \% \{ \\ …
                    continue;
                }
                let name = &text[i + 1..j];
                let Some(kind) = MarkKind::of(name) else {
                    i = j;
                    continue;
                };
                let Some((a0, a1)) = group(text, j) else {
                    i = j;
                    continue;
                };
                let id = text[a0 + 1..a1 - 1].trim().to_string();
                let (arg, end) = if kind == MarkKind::Dep {
                    (String::new(), a1)
                } else {
                    match group(text, a1) {
                        Some((g0, g1)) => (text[g0 + 1..g1 - 1].trim().to_string(), g1),
                        None => (String::new(), a1),
                    }
                };
                out.push(Mark { kind, id, arg, start: s, end });
                i = end;
                continue;
            }
            _ => {}
        }
        i += 1;
    }
    out
}

/// The ids marked in `text`.
pub fn ids(text: &str) -> BTreeSet<String> {
    marks(text).into_iter().map(|m| m.id).collect()
}

/// `text` with the marks of `id` filled in: a number or a cell becomes
/// `value(mark)` (left as it is when that gives None); a dependency mark goes,
/// with the blanks right before it. A planned paragraph (`\pendingpara`) is
/// never filled here — it has to be written.
pub fn fill(text: &str, id: &str, value: &dyn Fn(&Mark) -> Option<String>) -> String {
    let mut out = String::with_capacity(text.len());
    let mut at = 0;
    for m in marks(text).into_iter().filter(|m| m.id == id) {
        let new = match m.kind {
            MarkKind::Number | MarkKind::Cell => match value(&m) {
                Some(v) => v,
                None => continue,
            },
            MarkKind::Dep => String::new(),
            MarkKind::Para => continue,
        };
        let mut head = &text[at..m.start];
        if m.kind == MarkKind::Dep {
            head = head.trim_end_matches([' ', '\t']);
        }
        out += head;
        out += &new;
        at = m.end;
    }
    out += &text[at..];
    out
}

/// A text with every mark spelled out for a reader of plain text (slides, a
/// summary): `[pending: what]`, `[pending]` for a cell, `[pending: frame]` for
/// a paragraph, and ` [pending]` after a sentence that depends on one (it
/// states an expected result, not a finding). Never a number in place of a mark.
pub fn to_plain(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut at = 0;
    for m in marks(text) {
        out += &text[at..m.start];
        match m.kind {
            MarkKind::Number | MarkKind::Para if !m.arg.is_empty() => out += &format!("[pending: {}]", m.arg),
            MarkKind::Dep => {
                let kept = out.trim_end_matches([' ', '\t']).len();
                out.truncate(kept);
                out += " [pending]";
            }
            _ => out += "[pending]",
        }
        at = m.end;
    }
    out += &text[at..];
    out
}

/// The definitions: robust commands, boxed and in the draft colour when a
/// colour package is there. Colour is loaded at the end of the preamble only
/// when no colour package was (`color`, no options: nothing can clash after it).
/// ASCII only, so every engine compiles it.
pub fn tex() -> String {
    let (r, g, b) = DRAFT_RGB;
    format!(
        "{GENERATED_HEADER}\n\
% \\input{{pending}} in the preamble. Marks: \\pending{{id}}{{what}} \\pendingcell{{id}}{{cell}} \\pendingpara{{id}}{{frame}} \\pendingdep{{id}}.\n\
\\makeatletter\n\
\\ifdefined\\AddToHook\\AddToHook{{begindocument/before}}{{\\@ifpackageloaded{{xcolor}}{{}}{{\\@ifpackageloaded{{color}}{{}}{{\\RequirePackage{{color}}}}}}}}\\fi\n\
\\providecommand\\lorepend@color[1]{{\\ifdefined\\textcolor\\textcolor[rgb]{{{r:.2},{g:.2},{b:.2}}}{{#1}}\\else#1\\fi}}\n\
\\providecommand\\lorepend@box[1]{{\\lorepend@color{{\\fbox{{\\sffamily\\footnotesize #1}}}}}}\n\
\\DeclareRobustCommand\\pending[2]{{\\lorepend@box{{#1: #2}}}}\n\
\\DeclareRobustCommand\\pendingcell[2]{{\\lorepend@box{{#1}}}}\n\
\\DeclareRobustCommand\\pendingdep[1]{{\\textsuperscript{{\\lorepend@color{{\\sffamily[#1]}}}}}}\n\
\\DeclareRobustCommand\\pendingpara[2]{{\\par\\noindent\\lorepend@box{{PENDING #1}}\\enspace{{\\itshape\\lorepend@color{{#2}}}}\\par}}\n\
\\makeatother\n"
    )
}

/// A `pending.tex` this crate wrote.
pub fn is_generated(text: &str) -> bool {
    text.starts_with(GENERATED_HEADER)
}

/// Write the definitions next to the main file. A `pending.tex` there that this
/// crate did not write is never overwritten: the new one gets a free name
/// (`pending-2.tex`, …). Returns the path (its stem is what to `\input`).
pub fn write_tex(dir: &Path) -> std::io::Result<PathBuf> {
    let content = tex();
    let mut path = dir.join(FILE);
    let mut k = 2;
    loop {
        match std::fs::read_to_string(&path) {
            Ok(old) if is_generated(&old) => {
                if old == content {
                    return Ok(path);
                }
                break;
            }
            Ok(_) => {
                path = dir.join(format!("pending-{k}.tex"));
                k += 1;
            }
            Err(_) => break,
        }
    }
    crate::write_atomic(&path, &content)?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    const T: &str = "Dice reached \\pending{P1}{Dice on the external set} (\\ref{tab:ext}), \
higher than the baseline\\pendingdep{P1}. % \\pending{P9}{commented}\n\
\\begin{tabular}{lc}Ours & \\pendingcell{P2}{Ours / Dice} \\\\\\end{tabular}\n\
\\pendingpara{P3}{Compare the two sites in \\ref{tab:ext}; the main table holds it.}";

    #[test]
    fn finds_every_mark_with_its_id_and_argument() {
        let m = marks(T);
        assert_eq!(m.iter().map(|m| (m.kind, m.id.as_str())).collect::<Vec<_>>(), [
            (MarkKind::Number, "P1"),
            (MarkKind::Dep, "P1"),
            (MarkKind::Cell, "P2"),
            (MarkKind::Para, "P3")
        ]);
        assert_eq!(m[0].arg, "Dice on the external set");
        assert_eq!(&T[m[1].start..m[1].end], "\\pendingdep{P1}");
        assert!(m[3].arg.contains("\\ref{tab:ext}"), "nested braces stay in the argument");
        assert_eq!(ids(T).into_iter().collect::<Vec<_>>(), ["P1", "P2", "P3"], "a commented mark is not a mark");
        assert!(marks("\\pendingx{P1} \\pending").is_empty());
        assert!(valid_id("P1") && valid_id("abl-2") && !valid_id("1P") && !valid_id("P 1") && !valid_id(""));
    }

    #[test]
    fn filling_replaces_numbers_and_cells_and_drops_the_dependency() {
        let out = fill(T, "P1", &|_| Some("0.74".into()));
        assert!(out.starts_with("Dice reached 0.74 (\\ref{tab:ext}), higher than the baseline. %"), "{out}");
        assert!(out.contains("\\pendingcell{P2}"), "other ids stay");
        let cells = fill(T, "P2", &|m| (m.arg == "Ours / Dice").then(|| "0.81".into()));
        assert!(cells.contains("Ours & 0.81 \\\\"), "{cells}");
        assert_eq!(fill(T, "P2", &|_| None), T, "no value, no change");
        assert_eq!(fill(T, "P3", &|_| Some("x".into())), T, "a planned paragraph is written, never filled");
    }

    #[test]
    fn plain_text_shows_marks_and_never_a_number() {
        let p = to_plain(T);
        assert!(p.contains("Dice reached [pending: Dice on the external set] (") && p.contains("baseline [pending]. %"), "{p}");
        assert!(p.contains("Ours & [pending] \\\\") && p.contains("[pending: Compare the two sites"));
        assert!(!p.replace("% \\pending{P9}{commented}", "").contains("\\pending"), "only the comment keeps its mark");
    }

    #[test]
    fn definitions_are_ascii_and_kept_apart_from_a_users_file() {
        let t = tex();
        assert!(t.is_ascii() || t.lines().skip(1).all(|l| l.is_ascii()), "only the header comment may carry 待補");
        for m in MACROS {
            assert!(t.contains(&format!("\\DeclareRobustCommand\\{m}[")), "{m}");
        }
        assert!(t.contains("0.76,0.25,0.05"));
        let d = std::env::temp_dir().join(format!("lore-pending-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        assert_eq!(write_tex(&d).unwrap(), d.join(FILE));
        assert_eq!(write_tex(&d).unwrap(), d.join(FILE), "ours: rewritten in place");
        std::fs::write(d.join(FILE), "% the author's own\n").unwrap();
        assert_eq!(write_tex(&d).unwrap(), d.join("pending-2.tex"));
        assert_eq!(std::fs::read_to_string(d.join(FILE)).unwrap(), "% the author's own\n");
        let _ = std::fs::remove_dir_all(&d);
    }
}
