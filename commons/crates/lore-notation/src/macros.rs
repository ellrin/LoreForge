/// A valid, non-clobbering macro name (without backslash).
pub fn check_macro_name(name: &str, existing: &BTreeSet<String>) -> Result<(), String> {
    if name.is_empty() {
        return Err("巨集名稱不可空白".into());
    }
    if !name.chars().all(|c| c.is_ascii_alphabetic()) {
        return Err(format!("巨集 \\{name} 只能用英文字母（LaTeX 指令名稱不能有數字或符號）"));
    }
    if RESERVED.contains(&name) || math::is_greek(name) || name.starts_with("text") || name.starts_with("math") {
        return Err(format!("\\{name} 是 LaTeX 既有指令，不能覆蓋"));
    }
    if existing.contains(name) {
        return Err(format!("\\{name} 已在文件中定義"));
    }
    Ok(())
}

pub fn balanced(s: &str) -> bool {
    let mut d = 0i32;
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b'\\' => i += 1,
            b'{' => d += 1,
            b'}' => {
                d -= 1;
                if d < 0 {
                    return false;
                }
            }
            _ => {}
        }
        i += 1;
    }
    d == 0
}

/// What a macro expands to in LaTeX (inside `\newcommand{\m}{…}`), or None.
fn tex_body(e: &Entry, words: &RefWords) -> Option<(bool, String)> {
    let latex = e.latex.as_deref().map(str::trim).filter(|s| !s.is_empty());
    Some(match e.kind() {
        Kind::Symbol => (false, format!("\\ensuremath{{{}}}", latex?)),
        Kind::Operator => {
            let l = latex?;
            // \operatorname{mean} or a bare word → \DeclareMathOperator
            let word = l.strip_prefix("\\operatorname{").and_then(|r| r.strip_suffix('}')).unwrap_or(l);
            if word.chars().all(|c| c.is_ascii_alphanumeric() || c == ' ' || c == '-') {
                (true, word.to_string())
            } else {
                (false, format!("\\ensuremath{{{l}}}"))
            }
        }
        Kind::Equation => {
            let l = latex?;
            if l.contains('&') || l.contains("\\\\") { (false, l.to_string()) } else { (false, format!("\\ensuremath{{{l}}}")) }
        }
        Kind::Abbrev => (false, e.short.clone()?),
        Kind::Term => (false, e.meaning_en.clone().or(e.short.clone()).or(latex.map(String::from))?),
        Kind::Figure => (false, words.snippet("fig", e.label.as_deref()?, false)),
        Kind::Table => (false, words.snippet("tab", e.label.as_deref()?, false)),
    })
}

/// Contents of `notation.tex`. Entries with an invalid or clobbering macro
/// name are left out and listed as `% skipped` comments.
pub fn notation_tex(n: &Notation, existing: &BTreeSet<String>) -> String {
    notation_tex_with(n, existing, &RefWords::default())
}

/// [`notation_tex`] with a journal's reference words (figure and table macros
/// print `Figure~\ref{…}`, or `\cref{…}` in cleveref mode).
pub fn notation_tex_with(n: &Notation, existing: &BTreeSet<String>, words: &RefWords) -> String {
    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push('\n');
    out.push_str("% \\input{notation} in the preamble (after amsmath).\n");
    let mut seen = BTreeSet::new();
    for e in &n.entries {
        let Some(name) = e.macro_name() else { continue };
        if let Err(msg) = check_macro_name(name, existing) {
            out.push_str(&format!("% skipped {}: {msg}\n", e.id));
            continue;
        }
        if !seen.insert(name.to_string()) {
            out.push_str(&format!("% skipped {}: \\{name} 重複\n", e.id));
            continue;
        }
        let Some((op, body)) = tex_body(e, words) else {
            out.push_str(&format!("% skipped {}: 缺少內容\n", e.id));
            continue;
        };
        if !balanced(&body) {
            out.push_str(&format!("% skipped {}: 大括號不成對\n", e.id));
            continue;
        }
        let note = e.meaning.as_deref().or(e.meaning_en.as_deref()).map(|m| format!(" % {}", m.replace('\n', " "))).unwrap_or_default();
        if op {
            out.push_str(&format!("\\DeclareMathOperator{{\\{name}}}{{{body}}}{note}\n"));
        } else {
            out.push_str(&format!("\\newcommand{{\\{name}}}{{{body}}}{note}\n"));
        }
    }
    out
}

/// Write `notation.tex` into `dir`. A file there that lore-notation did not
/// generate is never overwritten: the new one gets a free name
/// (`notation-2.tex`, …). Returns the path written.
pub fn write_notation_tex(dir: &Path, n: &Notation, existing: &BTreeSet<String>) -> std::io::Result<PathBuf> {
    let content = notation_tex(n, existing);
    let mut path = dir.join("notation.tex");
    let mut k = 2;
    loop {
        match std::fs::read_to_string(&path) {
            Ok(old) if is_generated(&old) => break,
            Ok(_) => {
                path = dir.join(format!("notation-{k}.tex"));
                k += 1;
            }
            Err(_) => break,
        }
    }
    crate::write_atomic(&path, &content)?;
    Ok(path)
}

/// Macro map for KaTeX (`{"\\ribmask": "\\boldsymbol{m}"}`), for previews.
pub fn katex_macros(n: &Notation) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    for e in &n.entries {
        let Some(name) = e.macro_name() else { continue };
        if !name.chars().all(|c| c.is_ascii_alphabetic()) {
            continue;
        }
        let Some((op, body)) = tex_body(e, &RefWords::default()) else { continue };
        let body = if op {
            format!("\\operatorname{{{body}}}")
        } else if matches!(e.kind(), Kind::Abbrev | Kind::Term) {
            format!("\\text{{{body}}}")
        } else {
            body.strip_prefix("\\ensuremath{").and_then(|b| b.strip_suffix('}')).map(String::from).unwrap_or(body)
        };
        out.insert(format!("\\{name}"), body);
    }
    out
}

/// Macros as [`math::Macro`]s for the scanner (so `\ribmask` in the text
/// counts as `\boldsymbol{m}`).
pub fn scan_macros(n: &Notation) -> BTreeMap<String, math::Macro> {
    katex_macros(n).into_iter().map(|(k, v)| (k.trim_start_matches('\\').to_string(), math::Macro { nargs: 0, body: v })).collect()
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum InsertMode {
    /// `\ribmask` — change the table, every use follows.
    Macro,
    /// `\boldsymbol{m}` — plain LaTeX.
    Literal,
}

/// What an "插入" button puts at the caret. `in_math`: the caret is already
/// inside math. Macro mode falls back to literal when the entry has no macro.
pub fn insert_text(e: &Entry, mode: InsertMode, in_math: bool) -> String {
    insert_text_with(e, mode, in_math, &RefWords::default())
}

/// [`insert_text`] with a journal's reference words (mid-sentence form).
pub fn insert_text_with(e: &Entry, mode: InsertMode, in_math: bool, words: &RefWords) -> String {
    let mac = e.macro_name().filter(|_| mode == InsertMode::Macro);
    // in math a trailing control word (`\speed`, `\alpha`) gets a space so a
    // letter typed next does not merge into it (`\speedx`)
    let wrap = |s: String| if in_math { if ends_with_control_word(&s) { s + " " } else { s } } else { format!("${s}$") };
    match e.kind() {
        Kind::Symbol | Kind::Operator => match mac {
            Some(m) => wrap(format!("\\{m}")),
            None => wrap(e.latex.clone().unwrap_or_default()),
        },
        Kind::Equation => match (&e.label, mac) {
            (Some(l), _) if !in_math => words.snippet("eq", l, false),
            (_, Some(m)) => wrap(format!("\\{m}")),
            _ => wrap(e.latex.clone().unwrap_or_default()),
        },
        Kind::Figure | Kind::Table => match mac {
            Some(m) => format!("\\{m}{{}}"),
            None => words.snippet(if e.kind() == Kind::Figure { "fig" } else { "tab" }, e.label.as_deref().unwrap_or_default(), false),
        },
        Kind::Abbrev => match mac {
            Some(m) => format!("\\{m}{{}}"),
            None => e.short.clone().unwrap_or_default(),
        },
        Kind::Term => match mac {
            Some(m) => format!("\\{m}{{}}"),
            None => e.meaning_en.clone().or(e.meaning.clone()).unwrap_or_default(),
        },
    }
}

/// `\name` at the very end (a letter typed after it would join the name).
pub fn ends_with_control_word(s: &str) -> bool {
    let letters = s.chars().rev().take_while(|c| c.is_ascii_alphabetic()).count();
    letters > 0 && s[..s.len() - letters].ends_with('\\') && !s[..s.len() - letters - 1].ends_with('\\')
}

/// A Nomenclature table (symbols and operators, then abbreviations).
/// `lang`: "zh" uses `meaning`, anything else `meaning_en` (falling back to the other).
pub fn nomenclature_tex(n: &Notation, lang: &str) -> String {
    let meaning = |e: &Entry| {
        let (a, b) = if lang == "zh" { (&e.meaning, &e.meaning_en) } else { (&e.meaning_en, &e.meaning) };
        a.clone().or(b.clone()).unwrap_or_default()
    };
    let mut out = String::from("\\begin{tabular}{ll}\n\\hline\n");
    for e in n.entries.iter().filter(|e| matches!(e.kind(), Kind::Symbol | Kind::Operator)) {
        let sym = match e.macro_name() {
            Some(m) => format!("$\\{m}$"),
            None => format!("${}$", e.latex.clone().unwrap_or_default()),
        };
        let mut m = meaning(e);
        if let Some(u) = &e.unit {
            m.push_str(&format!(" [{u}]"));
        }
        out.push_str(&format!("{sym} & {m} \\\\\n"));
    }
    let abbr: Vec<&Entry> = n.entries.iter().filter(|e| e.kind() == Kind::Abbrev).collect();
    if !abbr.is_empty() {
        out.push_str("\\hline\n");
        for e in abbr {
            out.push_str(&format!("{} & {} \\\\\n", e.short.clone().unwrap_or_default(), e.long.clone().unwrap_or_else(|| meaning(e))));
        }
    }
    out.push_str("\\hline\n\\end{tabular}\n");
    out
}

/// Rename `\old` to `\new` in LaTeX source (whole command names only).
/// Returns the new text and the number of replacements.
pub fn rename_macro(text: &str, old: &str, new: &str) -> (String, usize) {
    let old = old.trim_start_matches('\\');
    let new = new.trim_start_matches('\\');
    let pat = format!("\\{old}");
    let mut out = String::with_capacity(text.len());
    let mut n = 0;
    let mut i = 0;
    while let Some(k) = text[i..].find(&pat) {
        let s = i + k;
        let after = s + pat.len();
        // preceded by an escaping backslash (\\old is a line break + "old")?
        let escaped = text[..s].chars().rev().take_while(|c| *c == '\\').count() % 2 == 1;
        let whole = !text[after..].starts_with(|c: char| c.is_ascii_alphabetic());
        out.push_str(&text[i..s]);
        if whole && !escaped {
            out.push('\\');
            out.push_str(new);
            n += 1;
        } else {
            out.push_str(&pat);
        }
        i = after;
    }
    out.push_str(&text[i..]);
    (out, n)
}

/// Replace every math occurrence of the symbol `old` (any spelling: `\bm{m}`,
/// `\mathbf m`, …) by `new` in one file's LaTeX. Subscripted uses keep their
/// subscripts only when `old` has none (`m_i` → `new_i` is not attempted:
/// such occurrences are counted in the second number and left alone).
pub fn replace_symbol(text: &str, old: &str, new: &str) -> (String, usize, usize) {
    let key = math::canonical(old);
    let scan = crate::scan::Scan::new(crate::source::Document::from_str("x.tex", &format!("\\begin{{document}}\n{text}\n\\end{{document}}")), Default::default());
    let shift = "\\begin{document}\n".len();
    let mut spans: Vec<(usize, usize)> = Vec::new();
    let mut skipped = 0;
    for seg in &scan.math {
        let mut v = Vec::new();
        math::collect_syms(&seg.atoms, &mut v);
        let mut stack = v;
        while let Some(s) = stack.pop() {
            stack.extend(s.qualifiers.iter().cloned());
            stack.extend(s.script_uses.iter().cloned());
            if s.key() == key {
                // the span covers the symbol and its scripts; only replace scriptless ones
                let src = &scan.doc.text[s.start..s.end.min(scan.doc.text.len())];
                if src.contains('_') || src.contains('^') {
                    skipped += 1;
                } else {
                    spans.push((s.start - shift, s.end - shift));
                }
            }
        }
    }
    spans.sort();
    spans.dedup();
    let mut out = String::new();
    let mut i = 0;
    let mut n = 0;
    for (s, e) in spans {
        if s < i || e > text.len() {
            continue;
        }
        out.push_str(&text[i..s]);
        out.push_str(new);
        i = e;
        n += 1;
    }
    out.push_str(&text[i..]);
    (out, n, skipped)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reg() -> Notation {
        let mut n = Notation::default();
        let mut a = Entry::new("mask", Kind::Symbol);
        a.latex = Some("\\boldsymbol{m}".into());
        a.macro_name = Some("\\wmask".into());
        a.meaning = Some("遮罩".into());
        let mut b = Entry::new("mean", Kind::Operator);
        b.latex = Some("\\operatorname{mean}".into());
        b.macro_name = Some("avg".into());
        let mut c = Entry::new("bad", Kind::Symbol);
        c.latex = Some("x".into());
        c.macro_name = Some("alpha".into());
        let mut d = Entry::new("wn", Kind::Abbrev);
        d.short = Some("WN".into());
        d.macro_name = Some("wn".into());
        n.entries = vec![a, b, c, d];
        n
    }

    #[test]
    fn generates_macros_and_refuses_clobbering() {
        let tex = notation_tex(&reg(), &BTreeSet::new());
        assert!(tex.starts_with(GENERATED_HEADER));
        assert!(tex.contains("\\newcommand{\\wmask}{\\ensuremath{\\boldsymbol{m}}} % 遮罩"));
        assert!(tex.contains("\\DeclareMathOperator{\\avg}{mean}"));
        assert!(tex.contains("% skipped bad"));
        assert!(tex.contains("\\newcommand{\\wn}{WN}"));
        let existing: BTreeSet<String> = ["wmask".to_string()].into();
        assert!(notation_tex(&reg(), &existing).contains("% skipped mask"));
        assert!(check_macro_name("x1", &BTreeSet::new()).is_err());
        assert!(check_macro_name("mathbold", &BTreeSet::new()).is_err());
        assert!(check_macro_name("ribmask", &BTreeSet::new()).is_ok());
    }

    #[test]
    fn katex_map_and_insert_text() {
        let n = reg();
        let k = katex_macros(&n);
        assert_eq!(k["\\wmask"], "\\boldsymbol{m}");
        assert_eq!(k["\\avg"], "\\operatorname{mean}");
        assert_eq!(k["\\wn"], "\\text{WN}");
        assert_eq!(insert_text(&n.entries[0], InsertMode::Macro, false), "$\\wmask$");
        assert_eq!(insert_text(&n.entries[0], InsertMode::Literal, true), "\\boldsymbol{m}");
        assert_eq!(insert_text(&n.entries[0], InsertMode::Macro, true), "\\wmask ", "a following letter must not join the macro name");
        assert!(ends_with_control_word("a+\\alpha") && !ends_with_control_word("x\\\\y") && !ends_with_control_word("\\bm{m}"));
        assert_eq!(insert_text(&n.entries[3], InsertMode::Literal, false), "WN");
        let mut f = Entry::new("f1", Kind::Figure);
        f.label = Some("fig:a".into());
        assert_eq!(insert_text(&f, InsertMode::Macro, false), "Fig.~\\ref{fig:a}");
        let mut t = Entry::new("t1", Kind::Table);
        t.label = Some("tab:a".into());
        assert_eq!(insert_text(&t, InsertMode::Macro, false), "Table~\\ref{tab:a}");
        let mut q = Entry::new("e1", Kind::Equation);
        q.label = Some("eq:a".into());
        assert_eq!(insert_text(&q, InsertMode::Macro, false), "\\eqref{eq:a}");
    }

    #[test]
    fn insert_text_follows_the_journal() {
        let mut f = Entry::new("f1", Kind::Figure);
        f.label = Some("fig:a".into());
        f.macro_name = Some("figa".into());
        let words = RefWords { fig: Some("Figure".into()), eq: Some("Eq.".into()), ..Default::default() };
        assert_eq!(insert_text_with(&f, InsertMode::Literal, false, &words), "Figure~\\ref{fig:a}");
        let mut q = Entry::new("e1", Kind::Equation);
        q.label = Some("eq:a".into());
        assert_eq!(insert_text_with(&q, InsertMode::Macro, false, &words), "Eq.~\\eqref{eq:a}");
        let mut n = Notation::default();
        n.entries = vec![f.clone()];
        assert!(notation_tex(&n, &BTreeSet::new()).contains("\\newcommand{\\figa}{Fig.~\\ref{fig:a}}"), "default unchanged");
        assert!(notation_tex_with(&n, &BTreeSet::new(), &words).contains("\\newcommand{\\figa}{Figure~\\ref{fig:a}}"));
        let c = RefWords { mode: Some("cleveref".into()), ..Default::default() };
        assert_eq!(insert_text_with(&f, InsertMode::Literal, false, &c), "\\cref{fig:a}");
    }

    #[test]
    fn writes_beside_a_user_file_never_over_it() {
        let dir = std::env::temp_dir().join(format!("lore-notation-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("notation.tex"), "% mine\n").unwrap();
        let p = write_notation_tex(&dir, &reg(), &BTreeSet::new()).unwrap();
        assert_eq!(p.file_name().unwrap(), "notation-2.tex");
        assert_eq!(std::fs::read_to_string(dir.join("notation.tex")).unwrap(), "% mine\n");
        // a generated file is refreshed in place
        let p2 = write_notation_tex(&dir, &reg(), &BTreeSet::new()).unwrap();
        assert_eq!(p2, p);
        // a file written under the crate's old name is still ours: refreshed in place
        std::fs::write(dir.join("notation.tex"), format!("{}\n\\newcommand{{\\old}}{{x}}\n", LEGACY_HEADERS[0])).unwrap();
        let p3 = write_notation_tex(&dir, &reg(), &BTreeSet::new()).unwrap();
        assert_eq!(p3.file_name().unwrap(), "notation.tex");
        assert!(std::fs::read_to_string(&p3).unwrap().starts_with(GENERATED_HEADER));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn rename_and_replace() {
        let (t, n) = rename_macro("$\\wmask + \\wmasks$ \\\\wmask", "wmask", "rmask");
        assert_eq!(t, "$\\rmask + \\wmasks$ \\\\wmask");
        assert_eq!(n, 1);
        let (t, n, skipped) = replace_symbol("Let $\\bm{m}$ and $\\mathbf m + m_i$ and $\\boldsymbol{m}^{\\mathrm{a}}$.", "\\boldsymbol{m}", "\\boldsymbol{r}");
        assert_eq!(t, "Let $\\boldsymbol{r}$ and $\\boldsymbol{r} + m_i$ and $\\boldsymbol{m}^{\\mathrm{a}}$.");
        assert_eq!((n, skipped), (2, 0));
    }
}
