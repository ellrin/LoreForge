use std::path::{Path, PathBuf};

pub const GENERATED_HEADER: &str = "% Generated by lore-notation from notation.json — edit the table, not this file.";
/// The header files carried before the crate was renamed; still ours.
pub const LEGACY_HEADERS: &[&str] = &["% Generated by ym-notation from notation.json — edit the table, not this file."];

/// A `notation.tex` this crate wrote (under its current or an earlier name).
pub fn is_generated(text: &str) -> bool {
    text.starts_with(GENERATED_HEADER) || LEGACY_HEADERS.iter().any(|h| text.starts_with(h))
}

