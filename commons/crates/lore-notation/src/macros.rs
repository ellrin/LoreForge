//! Macro mode: `notation.tex` with one `\newcommand` per entry that has a
//! `macro`, so changing the table changes every use. Also the KaTeX macro
//! map for previews, the text an "插入" button puts in, a Nomenclature
//! table, and source rewrites (rename a macro, replace a symbol).

