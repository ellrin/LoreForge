//! 開啟 LaTeX… / 開啟 Word… through the HTTP API, on a server of its own
//! with a temporary workspace, home and list of opened folders (this test
//! binary is its own process, so the environment it sets stays here).

use serde_json::{json, Value};
use std::path::{Path, PathBuf};

struct Api {
    base: String,
    http: reqwest::Client,
}

impl Api {
    async fn get(&self, path: &str) -> (u16, Value) {
        let r = self.http.get(format!("{}{path}", self.base)).send().await.unwrap();
        let code = r.status().as_u16();
        (code, r.json().await.unwrap_or(Value::Null))
    }
    async fn send(&self, method: reqwest::Method, path: &str, body: Value) -> (u16, Value) {
        let r = self.http.request(method, format!("{}{path}", self.base)).json(&body).send().await.unwrap();
        let code = r.status().as_u16();
        let text = r.text().await.unwrap();
        (code, serde_json::from_str(&text).unwrap_or(Value::String(text)))
    }
    async fn post(&self, path: &str, body: Value) -> (u16, Value) {
        self.send(reqwest::Method::POST, path, body).await
    }
    async fn put(&self, path: &str, body: Value) -> (u16, Value) {
        self.send(reqwest::Method::PUT, path, body).await
    }
}

fn enc(s: &str) -> String {
    s.replace(' ', "%20")
}

fn files_under(dir: &Path) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(dir).unwrap().flatten().map(|e| e.file_name().to_string_lossy().to_string()).collect();
    v.sort();
    v
}

#[tokio::test]
async fn opens_latex_and_word_where_they_are() {
    let root = std::env::temp_dir().join(format!("pc-open-api-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    for d in ["ws/papers", "ws/profile", "home", "private", "Projects"] {
        std::fs::create_dir_all(root.join(d)).unwrap();
    }
    // SAFETY: set before the server starts, in a test binary with this one test.
    unsafe {
        std::env::set_var("PAPERCOMPOSER_WORKSPACE", root.join("ws"));
        std::env::set_var("PAPERCOMPOSER_OPENED", root.join("home/opened.toml"));
        std::env::set_var("LOREFORGE_PRIVATE", root.join("private"));
        std::env::set_var("PAPERCOMPOSER_ENGINES_ISOLATED", "1");
        std::env::set_var("HOME", root.join("home"));
    }
    let (addr, serve) = pc_server::bind(pc_server::Paths::from_repo(), 0).await.unwrap();
    tokio::spawn(serve);
    let api = Api { base: format!("http://{addr}"), http: reqwest::Client::new() };
    let (_, ws) = api.get("/api/workspace").await;
    assert_eq!(ws["root"].as_str().map(PathBuf::from), Some(root.join("ws")));
    assert_eq!(ws["shell"], "browser");
    let ui = api.http.get(format!("{}/app.js", api.base)).send().await.unwrap();
    assert_eq!(ui.headers().get("cache-control").map(|v| v.to_str().unwrap()), Some("no-cache"), "a new server must not meet an old script");
    assert_eq!(api.post("/api/shell/dialog", json!({"kind": "latex"})).await.0, 501, "no native dialog in browser mode");

    // a co-author's project: ms.tex with an \input, notation in the preamble
    let proj = root.join("Projects/Joint paper");
    std::fs::create_dir_all(&proj).unwrap();
    std::fs::write(proj.join("ms.tex"), "\\documentclass{article}\n\\input{notation}\n\\begin{document}\n\\section{Intro}\n\\input{intro}\n\\end{document}\n").unwrap();
    std::fs::write(proj.join("notation.tex"), "% generated by lore-notation\n").unwrap();
    std::fs::write(proj.join("intro.tex"), "One sentence. Another one.\n").unwrap();
    let before = files_under(&proj);

    let (code, v) = api.post("/api/open/inspect", json!({"path": proj})).await;
    assert_eq!(code, 200, "{v}");
    assert_eq!(v["kind"], "latex");
    assert_eq!(v["plan"]["sections"], json!([["intro.tex", "Intro"]]), "the sections are the ones its main file inputs");
    assert_eq!(v["plan"]["created"], json!(["main.tex", "sections/01-intro.tex"]), "what 整理成章節檔 would do");
    assert_eq!(files_under(&proj), before, "the preview writes nothing");
    // 確定: as it is, only .papercomposer/ is added
    let (code, v) = api.post("/api/open/latex", json!({"path": proj, "stamp": v["plan"]["stamp"]})).await;
    assert_eq!(code, 200, "{v}");
    let id = v["id"].as_str().unwrap().to_string();
    assert_eq!(id, "Joint paper");
    assert_eq!(files_under(&proj), [".papercomposer", "intro.tex", "ms.tex", "notation.tex"], "no rename, no merge, no move");
    assert!(std::fs::read_to_string(proj.join("ms.tex")).unwrap().contains("\\input{intro}"));
    // a second open goes straight in
    let (_, again) = api.post("/api/open/inspect", json!({"path": proj.join("intro.tex")})).await;
    assert_eq!((again["kind"].as_str(), again["id"].as_str()), (Some("paper"), Some(id.as_str())));

    // edit in place
    let p = format!("/api/papers/{}", enc(&id));
    let (code, paper) = api.get(&p).await;
    assert_eq!(code, 200);
    assert_eq!(paper["path"].as_str().map(PathBuf::from), Some(proj.clone()));
    let sec = paper["sections"][0].clone();
    assert_eq!(sec["paragraphs"], json!(["One sentence. Another one."]));
    let (code, saved) = api
        .put(&format!("{p}/sections/intro.tex"), json!({"title": "Intro", "paragraphs": ["One sentence, edited."], "base": {"title": sec["title"], "paragraphs": sec["paragraphs"]}}))
        .await;
    assert_eq!(code, 200, "{saved}");
    assert!(std::fs::read_to_string(proj.join("intro.tex")).unwrap().contains("One sentence, edited."));
    let stamp = saved["stamp"].clone();
    assert_eq!(api.get(&format!("{p}/stamp")).await.1["stamp"], stamp);

    // edited in another editor: the stamp moves, a save from the old text is refused
    std::fs::write(proj.join("intro.tex"), "\\section{Intro}\n\nChanged elsewhere.\n").unwrap();
    assert_ne!(api.get(&format!("{p}/stamp")).await.1["stamp"], stamp);
    let (code, v) = api
        .put(&format!("{p}/sections/intro.tex"), json!({"title": "Intro", "paragraphs": ["Mine."], "base": {"title": "Intro", "paragraphs": ["One sentence, edited."]}}))
        .await;
    assert_eq!(code, 409);
    assert_eq!(v["section"]["paragraphs"], json!(["Changed elsewhere."]));
    // 保留我的版本
    let (code, _) = api.put(&format!("{p}/sections/intro.tex"), json!({"title": "Intro", "paragraphs": ["Mine."]})).await;
    assert_eq!(code, 200);

    // PaperComposer's own files go into .papercomposer/, not the project's top level
    assert_eq!(api.put(&format!("{p}/review/tracking"), json!({"on": true})).await.0, 200);
    assert_eq!(api.post(&format!("{p}/citations"), json!({"key": "k1", "purpose": "Intro"})).await.0 / 100, 2);
    let app = files_under(&proj.join(".papercomposer"));
    assert!(app.contains(&"review.json".into()) && app.contains(&"citations.csv".into()) && app.contains(&"paper.toml".into()), "{app:?}");
    assert_eq!(files_under(&proj), [".papercomposer", "intro.tex", "ms.tex", "notation.tex"]);

    // the start screen and the recent list
    let (_, cards) = api.get("/api/home/papers").await;
    assert!(cards.as_array().unwrap().iter().any(|c| c["name"] == id.as_str() && c["path"].as_str().is_some()));
    let (_, recent) = api.get("/api/open/recent").await;
    assert_eq!((recent[0]["id"].as_str(), recent[0]["exists"].as_bool()), (Some(id.as_str()), Some(true)));
    assert!(ws_names(&api).await.contains(&id), "a new paper cannot take its name");

    // .zip: unpacked beside it, then like a folder
    let zip = root.join("Projects/Shared.zip");
    {
        use std::io::Write;
        let mut z = zip::ZipWriter::new(std::fs::File::create(&zip).unwrap());
        z.start_file("main.tex", zip::write::SimpleFileOptions::default()).unwrap();
        z.write_all(b"\\documentclass{article}\n\\begin{document}\n\\section{A}\nText.\n\\end{document}\n").unwrap();
        z.finish().unwrap();
    }
    let (_, v) = api.post("/api/open/inspect", json!({"path": zip})).await;
    assert_eq!(v["kind"], "archive");
    assert_eq!(v["dest"].as_str().map(PathBuf::from), Some(root.join("Projects/Shared")));
    let (code, v) = api.post("/api/open/extract", json!({"path": zip, "dest": v["dest"]})).await;
    assert_eq!((code, v["kind"].as_str()), (200, Some("latex")), "{v}");
    assert!(!root.join("Projects/Shared/sections").exists(), "unpacked, not restructured yet");
    // no sections in separate files: opening as it is says so; 整理成章節檔 backs up first
    assert_eq!(v["plan"]["sections"], json!([]));
    let shared = root.join("Projects/Shared");
    let (code, _) = api.post("/api/open/latex", json!({"path": v["path"], "stamp": v["plan"]["stamp"]})).await;
    assert_eq!(code, 400);
    assert!(!shared.join(".papercomposer").exists());
    let original = std::fs::read(shared.join("main.tex")).unwrap();
    let (code, w) = api.post("/api/open/latex", json!({"path": v["path"], "stamp": v["plan"]["stamp"], "restructure": true})).await;
    assert_eq!(code, 200, "{w}");
    assert!(shared.join("sections").is_dir());
    assert_eq!(std::fs::read(shared.join(".papercomposer/original/main.tex")).unwrap(), original, "the original is kept");

    // Word: a new LaTeX folder beside the .docx, tracked changes in the review
    let docx = root.join("Projects/Widgets.docx");
    std::fs::write(&docx, pc_server::word::synth::docx()).unwrap();
    let (_, v) = api.post("/api/open/inspect", json!({"path": docx})).await;
    assert_eq!(v["kind"], "word");
    assert_eq!(v["dest"].as_str().map(PathBuf::from), Some(root.join("Projects/Widgets (LaTeX)")));
    if v["pandoc"] == true {
        let (code, w) = api.post("/api/open/word", json!({"path": docx, "dest": v["dest"]})).await;
        assert_eq!(code, 200, "{w}");
        assert_eq!(w["id"], "Widgets LaTeX");
        assert_eq!(w["converted"]["changes"], 3);
        let (_, r) = api.get("/api/papers/Widgets%20LaTeX/review").await;
        assert_eq!(r["changes"].as_array().unwrap().len(), 3);
        assert!(r["changes"].as_array().unwrap().iter().all(|c| c["source"] == "word" && c["author"] == "daidai"));
        assert_eq!(r["comments"][0]["text"], "Please cite a second source here.");
        let (_, recent) = api.get("/api/open/recent").await;
        assert_eq!(recent[0]["kind"], "word");
    }

    // a folder that is gone: greyed in the list, 404 for the paper
    std::fs::rename(&proj, root.join("Projects/elsewhere")).unwrap();
    let (_, recent) = api.get("/api/open/recent").await;
    let gone = recent.as_array().unwrap().iter().find(|r| r["id"] == id.as_str()).unwrap();
    assert_eq!(gone["exists"], false);
    assert_eq!(api.get(&p).await.0, 404);
    assert_eq!(api.post("/api/open/forget", json!({"id": id})).await.0, 200);
    assert!(!api.get("/api/open/recent").await.1.as_array().unwrap().iter().any(|r| r["id"] == id.as_str()));
    let _ = std::fs::remove_dir_all(&root);
}

async fn ws_names(api: &Api) -> Vec<String> {
    let (_, ws) = api.get("/api/workspace").await;
    ws["papers"].as_array().unwrap().iter().filter_map(|x| x.as_str().map(String::from)).collect()
}
